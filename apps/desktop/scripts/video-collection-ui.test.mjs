import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from '../../html-renderer/node_modules/playwright/index.mjs';
await mkdir('.tmp/video-collection',{recursive:true});
const server = await createServer({configFile:false,root:process.cwd(),cacheDir:'.tmp/video-collection/vite',optimizeDeps:{entries:['scripts/fixtures/video-collection/preview.html']},server:{host:'127.0.0.1',port:1673,strictPort:true,hmr:false,watch:null}});
await server.listen();
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:900,height:800}});
try {
  await page.goto('http://127.0.0.1:1673/scripts/fixtures/video-collection/preview.html');
  const dialog = page.getByRole('dialog',{name:'采集视频'});
  await dialog.waitFor({timeout:10000});
  assert.equal(await page.evaluate(() => window.calls.filter(c=>c.command==='ensure-project').length),0,'opening/listing does not materialize a project');
  await page.getByRole('textbox',{name:'视频链接'}).fill('https://example.com/video.mp4');
  await page.evaluate(() => {window.failEnsure=true;});
  await page.getByRole('button',{name:'获取视频',exact:true}).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await page.evaluate(() => window.calls.filter(c=>c.args.action==='create').length),0,'failed materialization must not start a download');
  await page.getByRole('button',{name:'获取视频',exact:true}).click();
  await page.getByText('1.0 MB',{exact:true}).waitFor();
  assert.ok(await page.evaluate(() => window.calls.findIndex(c=>c.command==='ensure-project') >= 0 && window.calls.findIndex(c=>c.command==='ensure-project') < window.calls.findIndex(c=>c.args.action==='create')),'materialize before starting acquisition');
  assert.equal(await page.locator('progress').count(),0,'unknown total does not invent a percentage');
  await page.getByRole('button',{name:'取消获取'}).click();
  await page.getByText('已取消视频获取').waitFor();
  await page.getByRole('button',{name:'重新获取'}).click();
  await page.evaluate(() => {window.failSave=true;});
  await page.getByRole('button',{name:'保存到素材库'}).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await page.evaluate(() => {const at=window.calls.findIndex(c=>c.args.action==='save');return window.calls[at-1].command;}),'ensure-project','materialize before native save');
  assert.equal((await dialog.innerText()).includes('C:/private'),false);
  await page.getByRole('button',{name:'保存到素材库'}).click();
  assert.deepEqual(await page.evaluate(() => window.collected.map(item => [item.owner,item.addToCanvas])),[['original',false]]);
  const savedCalls = await page.evaluate(() => window.calls.filter(c=>c.args.action==='save').length);
  await page.evaluate(() => {window.failCallback=true;});
  await page.getByRole('button',{name:'添加到画板'}).click();
  await page.getByRole('alert').waitFor();
  await page.evaluate(() => {window.holdCallback=true;});
  await page.getByRole('button',{name:'添加到画板'}).click();
  await page.waitForFunction(() => !!window.releaseCallback);
  await page.evaluate(() => {window.switchProject();window.releaseCallback();});
  await page.waitForFunction(() => window.collected.length===2);
  assert.equal(await page.evaluate(() => window.collected[1].owner),'original','late save remains in frozen project');
  assert.equal(await page.evaluate(() => window.calls.filter(c=>c.args.action==='save').length),savedCalls,'canvas retry reuses saved asset');
  await page.setViewportSize({width:420,height:720});
  await page.screenshot({path:'.tmp/video-collection/narrow.png'});
  assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth),'narrow dialog does not overflow');
  await page.goto('http://127.0.0.1:1673/scripts/fixtures/video-collection/preview.html?theme=dark&global');
  await dialog.waitFor();
  await page.getByRole('textbox',{name:'视频链接'}).fill('https://v.douyin.com/example/');
  await page.getByRole('button',{name:'获取视频',exact:true}).click();
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('button',{name:'打开采集'}).click();
  await page.getByRole('button',{name:'取消获取'}).waitFor();
  await page.evaluate(() => {Object.assign(window.tasks[0],{kind:'douyin',state:'needs_login',message:'请打开抖音窗口继续获取'});});
  await page.getByRole('button',{name:'打开抖音窗口'}).click();
  await page.getByRole('button',{name:'保存到素材库'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'添加到画板'}).count(),0,'global collection does not invent a canvas target');
  await page.getByRole('button',{name:'保存到素材库'}).click();
  assert.equal(await page.evaluate(() => window.collected[0].owner),null);
  await page.screenshot({path:'.tmp/video-collection/dark.png'});
  console.log('video collection UI passed: progress, cancellation, save retry, frozen ownership, narrow layout');
} finally {await browser.close(); await server.close();}
