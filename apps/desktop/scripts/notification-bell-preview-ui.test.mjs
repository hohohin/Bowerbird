import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from '../../html-renderer/node_modules/playwright/index.mjs';
const server=await createServer({cacheDir:'.tmp/notification-bell-vite',server:{host:'127.0.0.1',port:1593,strictPort:true,hmr:false,watch:null}});
await server.listen();
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1000,height:700}});
page.setDefaultTimeout(3500);
const errors=[];page.on('pageerror',error=>errors.push(error.message));
try {
  await page.clock.install({time:new Date('2026-11-03T00:00:00Z')});
  await page.clock.pauseAt(new Date('2026-11-03T00:00:01Z'));
  await page.goto(`${server.resolvedUrls.local[0]}scripts/fixtures/notifications-scrollbars/bell-test.html`);
  const bell=page.getByRole('button',{name:/^通知/});
  await bell.waitFor();
  assert.equal(await page.getByRole('dialog').count(),0,'closed bell is the only permanent UI');
  await page.evaluate(()=>window.notice('第一张完成'));
  const latest=page.getByRole('dialog',{name:'新通知'});
  await latest.waitFor();
  assert.equal(await latest.getByRole('listitem').count(),1,'automatic opening contains only the new message');
  assert.equal(await page.locator('.app-toast').count(),0,'completion never duplicates as a toast');
  await page.clock.runFor(3999);assert.equal(await latest.count(),1);
  await page.clock.runFor(2);assert.equal(await latest.count(),0,'idle closes at four seconds');
  await page.evaluate(()=>window.notice('连续消息一'));
  await latest.waitFor();await page.clock.runFor(3000);
  await page.evaluate(()=>window.notice('连续消息二'));
  await latest.getByText('快速生成 · 连续消息二',{exact:true}).waitFor();
  await page.clock.runFor(1001);assert.equal(await latest.count(),1,'new message resets the idle timer');
  await page.clock.runFor(2999);assert.equal(await latest.count(),0);
  await bell.focus();await page.keyboard.press('Enter');
  const history=page.getByRole('dialog',{name:'通知历史'});
  await history.waitFor();
  assert.equal(await history.getByRole('listitem').first().getByRole('button').evaluate(element=>document.activeElement===element),true,'manual keyboard open focuses the first task');
  assert.equal(await history.getByRole('listitem').count(),2,'manual history retains running and completed tasks');
  await page.evaluate(()=>window.notice('阅读历史时完成'));
  assert.equal(await history.count(),1,'new messages do not replace manually opened history');
  await page.clock.runFor(5000);assert.equal(await history.count(),1,'manual history does not auto-close');
  await page.keyboard.press('Escape');assert.equal(await history.count(),0);
  assert.equal(await bell.evaluate(element=>document.activeElement===element),true,'Escape returns focus to bell');
  assert.equal(await bell.locator('i').count(),1,'project task unread remains after manual history is closed');
  await page.locator('#outside').click();
  await page.evaluate(()=>window.notice('第二张完成'));
  assert.equal(await page.locator('#outside').evaluate(element=>document.activeElement===element),true,'automatic notices do not steal focus');
  await latest.hover();await page.clock.runFor(4500);await page.mouse.move(15,200);
  await page.clock.runFor(4500);assert.equal(await latest.count(),1,'interaction keeps message readable after pointer leaves');
  await page.evaluate(()=>window.notice('第三张完成'));
  assert.equal(await latest.getByText('快速生成 · 第二张完成',{exact:true}).count(),1,'new arrivals do not replace an actively read message');
  await latest.getByRole('button',{name:'快速生成 · 第二张完成，查看画板'}).click();
  assert.deepEqual(await page.evaluate(()=>window.opened),['第二张完成']);
  assert.equal(await latest.count(),0,'opening the destination closes the notification');
  await page.locator('#outside').click();
  await page.evaluate(()=>window.notice('第四张完成'));
  await latest.getByRole('button',{name:'快速生成 · 第四张完成，查看画板'}).focus();
  await page.clock.runFor(4500);assert.equal(await latest.count(),1,'keyboard interaction pins automatic message');
  await page.keyboard.press('Escape');
  await page.evaluate(()=>window.notify('已保存','success'));
  await page.getByRole('status').filter({hasText:'已保存'}).waitFor();
  assert.equal(await page.getByRole('dialog').count(),0,'ordinary notices keep original toast behavior');
  await page.evaluate(()=>window.notify('文件已被占用，请关闭其他程序后重试','error'));
  await page.getByRole('status').filter({hasText:'文件已被占用，请关闭其他程序后重试'}).waitFor();
  assert.equal(await page.getByRole('dialog').count(),0,'ordinary errors stay in the toast viewport');
  await page.evaluate(()=>window.notice('关闭完成弹窗',{settings:{generation_completion_popup:false,generation_completion_sound:false}}));
  assert.equal(await page.getByRole('dialog').count(),0,'completion popup opt-out is respected');
  await page.clock.runFor(5000);
  await bell.click();await history.waitFor();await page.clock.runFor(200);
  await mkdir('.tmp/notifications-scrollbars',{recursive:true});
  await page.screenshot({path:'.tmp/notifications-scrollbars/bell-dark.png',animations:'disabled'});
  await page.evaluate(()=>document.documentElement.dataset.theme='light');
  await page.screenshot({path:'.tmp/notifications-scrollbars/bell-light.png',animations:'disabled'});
  await history.getByRole('button',{name:'快速生成 · 秋日图册 · 已完成，查看画板'}).click();
  assert.equal(await history.count(),0,'history task navigation also closes the panel');
  const navigation=await page.evaluate(()=>window.navigation());
  assert.equal(navigation.projectId,'quick');assert.equal(navigation.threadId,'thread-秋日图册');
  assert.ok(navigation.nodeId.includes('turn-秋日图册'),'history reuses the original task locator');
  assert.deepEqual(errors,[]);
  console.log('PASS candidate bell: single new message, four-second idle close, interaction pin, history, navigation, outside/Escape, generic toast and opt-out');
} finally {await browser.close();await server.close();}
