import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from '../../html-renderer/node_modules/playwright/index.mjs';

const server = await createServer({ cacheDir: '.tmp/collection-delete-actions/vite', server: { host: '127.0.0.1', port: 17931, strictPort: true, hmr: false, watch: null } });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 840 }, reducedMotion: 'reduce' });
page.setDefaultTimeout(5000);
const errors = [], remote = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('**/*', route => { if (new URL(route.request().url()).hostname === '127.0.0.1') return route.continue(); remote.push(route.request().url()); return route.abort(); });
const card = id => page.locator(`[data-connection-entry="${id}"] .folder-media-card`);
const action = name => page.getByRole('menuitem', { name, exact: true });
const dialog = () => page.getByRole('dialog');
async function open() {
  await page.goto('http://127.0.0.1:17931/scripts/fixtures/connected-collections/preview.html');
  await page.locator('[data-collection-id="child"]').click();
  await card('ref-one').waitFor();
}
async function menu(id) { await card(id).click({ button: 'right' }); await action('删除').click(); }
try {
  await mkdir('.tmp/collection-delete-actions', { recursive: true });
  await open(); await menu('ref-one');
  assert.deepEqual(await page.getByRole('menu', { name: '删除', exact: true }).getByRole('menuitem').allTextContents(), ['移出该集合', '删除原文件']);
  await page.screenshot({ path: '.tmp/collection-delete-actions/reference-menu-dark.png' });
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; });
  await page.waitForTimeout(180);
  await page.screenshot({ path: '.tmp/collection-delete-actions/reference-menu-light.png' });
  await action('移出该集合').click();
  await dialog().getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await page.evaluate(() => window.requests.filter(item => item.command === 'remove_connection_references').length), 0);
  await menu('ref-one'); await action('移出该集合').click();
  await dialog().getByRole('button', { name: '移出该集合', exact: true }).click();
  await dialog().waitFor({ state: 'detached' });
  assert.ok(await page.evaluate(() => window.entries.some(item => item.id === 'root-0') && window.entries.some(item => item.id === 'ref-two') && !window.entries.some(item => item.id === 'ref-one')));
  assert.deepEqual(await page.evaluate(() => window.requests.find(item => item.command === 'remove_connection_references').args), { ids: ['ref-one'] });
  await open(); await menu('child-0');
  assert.equal(await action('移出该集合').count(), 0, 'original entries cannot be removed as a reference');
  assert.equal(await action('删除原文件').count(), 1);
  await open(); await menu('ref-one'); await action('删除原文件').click();
  await dialog().getByText('/fixture/root-0.png', { exact: true }).waitFor();
  assert.equal(await dialog().getByText('/fixture/child/ref-one', { exact: true }).count(), 0, 'confirmation names the original, not the alias path');
  assert.equal(await page.evaluate(() => window.requests.filter(item => item.command === 'trash_asset_original').length), 0, 'opening a confirmation does not trash a file');
  await page.screenshot({ path: '.tmp/collection-delete-actions/original-confirmation.png' });
  await dialog().getByRole('button', { name: '删除原文件', exact: true }).click();
  await dialog().waitFor({ state: 'detached' });
  assert.deepEqual(await page.evaluate(() => window.requests.find(item => item.command === 'trash_asset_original').args), { original: { asset_id: 'root-0', name: 'root-0.png', path: '/fixture/root-0.png', fingerprint: 'fingerprint-root-0' } });
  assert.ok(await page.evaluate(() => !window.entries.some(item => item.id === 'root-0') && ['ref-one', 'ref-two'].every(id => window.entries.some(item => item.id === id && !item.available))), 'original deletion preserves other aliases as missing');
  await open(); await card('ref-one').click({ modifiers: ['Control'] }); await card('ref-two').click({ modifiers: ['Control'] });
  await menu('ref-two'); await action('删除原文件').click();
  await dialog().getByText('/fixture/root-0.png', { exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => window.requests.find(item => item.command === 'preview_asset_originals').args.assetIds), ['root-0'], 'multiple aliases resolve the original once');
  await dialog().getByRole('button', { name: '取消', exact: true }).click();
  await page.locator('.connected-selection').getByRole('button', { name: '删除', exact: true }).click();
  await action('移出该集合').click();
  await dialog().getByRole('button', { name: '移出该集合', exact: true }).click();
  await dialog().waitFor({ state: 'detached' });
  assert.deepEqual(await page.evaluate(() => window.requests.find(item => item.command === 'remove_connection_references').args.ids), ['ref-one', 'ref-two']);
  assert.ok(await page.evaluate(() => window.entries.some(item => item.id === 'root-0')));
  await open(); await card('child-0').click({ modifiers: ['Control'] }); await card('ref-one').click({ modifiers: ['Control'] });
  await page.locator('.connected-selection').getByRole('button', { name: '删除', exact: true }).click();
  assert.equal(await action('移出该集合').count(), 0, 'mixed selection never silently removes only the aliases');
  await action('删除原文件').click(); await dialog().getByText('/fixture/child-0.png', { exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => window.requests.find(item => item.command === 'preview_asset_originals').args.assetIds), ['child-0', 'root-0']);
  await dialog().getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await page.evaluate(() => window.requests.filter(item => item.command === 'trash_asset_original' || item.command === 'remove_connection_references').length), 0);
  await open(); await page.evaluate(() => { window.failReference = '无法移到系统回收站，文件已保留；请检查权限或手动处理'; });
  await menu('ref-one'); await action('移出该集合').click(); await dialog().getByRole('button', { name: '移出该集合', exact: true }).click();
  await dialog().getByRole('alert').waitFor();
  assert.ok(await page.evaluate(() => window.entries.some(item => item.id === 'ref-one') && window.entries.some(item => item.id === 'root-0')));
  await dialog().getByRole('button', { name: '取消', exact: true }).click();
  await open(); await page.evaluate(() => { window.entries.find(item => item.id === 'ref-one').available = false; window.changed(); });
  await page.locator('[data-connection-entry="ref-one"] .connected-missing').waitFor();
  await menu('ref-one'); await action('移出该集合').click(); await dialog().getByRole('button', { name: '移出该集合', exact: true }).click();
  await dialog().waitFor({ state: 'detached' });
  assert.ok(await page.evaluate(() => !window.entries.some(item => item.id === 'ref-one')), 'a missing original does not prevent removing its reference');
  assert.deepEqual(errors, []); assert.deepEqual(remote, []);
  await writeFile('.tmp/collection-delete-actions/result.json', JSON.stringify({ passed: true, errors, remote, boundary: 'real collection components with controlled IPC' }, null, 2));
  console.log('PASS collection deletion: reference/original identity, cancellation, duplicate/mixed selection, failure and themes');
} finally { await browser.close(); await server.close(); }
