import assert from 'node:assert/strict';
import { mkdir, copyFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { createServer } from 'vite';
import { chromium } from '../../html-renderer/node_modules/playwright/index.mjs';

const dir = '.tmp/video-trim'; await mkdir(dir, { recursive: true });
const ffmpeg = process.env.BOWERBIRD_FFMPEG_BINARY || resolve('../../.tmp/video-integration/tools/local/ffmpeg.exe');
const source = resolve(`${dir}/source.mp4`);
execFileSync(ffmpeg, ['-v', 'error', '-y', '-f', 'lavfi', '-i', 'color=teal:s=720x1280:r=25:d=3', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', source]);
const server = await createServer({ configFile: false, root: process.cwd(), cacheDir: `${dir}/vite`, server: { host: '127.0.0.1', port: 1649, strictPort: true, hmr: false, watch: null } });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
let encodes = 0;
await page.exposeFunction('trimFixture', async request => {
  const file = `${dir}/trim-${++encodes}.mp4`;
  execFileSync(ffmpeg, ['-v', 'error', '-y', '-i', source, '-ss', String(request.start), '-t', String(request.end - request.start), '-c:v', 'libx264', '-pix_fmt', 'yuv420p', file]);
  if (request.overwrite) await copyFile(file, source);
  return { store_path: request.overwrite ? '/.tmp/video-trim/source.mp4' : `/${file}` };
});
const dialog = page.getByRole('dialog', { name: /媒体预览/ });
const start = page.getByRole('spinbutton', { name: '入点秒数' });
const end = page.getByRole('spinbutton', { name: '出点秒数' });
const copies = () => page.evaluate(() => window.calls.filter(call => call.command === 'trim_video'));
try {
  await page.goto('http://127.0.0.1:1649/scripts/fixtures/canvas-reference/preview.html?strict');
  await page.locator('[data-canvas-node-id="old"]').waitFor();
  await page.evaluate(() => {
    const snapshot = window.snapshot();
    snapshot.nodes = [{ ...snapshot.nodes[0], id: 'clip', assetId: 'clip', x: 180, y: 120, width: 260, height: 462,
      payloadJson: JSON.stringify({ schema_version: 1, snapshot: { name: '裁剪测试', width: 720, height: 1280 } }) }];
    snapshot.view = { ...snapshot.view, zoom: 1, panX: 0, panY: 0 };
    sessionStorage.setItem('reference-fixture', JSON.stringify(snapshot));
    sessionStorage.setItem('reference-drafts', JSON.stringify([{ id: 'clip', name: '裁剪测试', ext: 'mp4', width: 720, height: 1280, store_path: '/.tmp/video-trim/source.mp4', duration: 3 }]));
  });
  await page.reload();
  await page.locator('[data-canvas-node-id="clip"]').focus(); await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('.video-player video')?.readyState >= 2);
  await page.getByRole('button', { name: '裁剪视频', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '另存为新视频', exact: true }).isDisabled(), true);
  await start.fill('1.1'); await end.fill('1.9');
  assert.match(await page.locator('.video-player-trim > span').innerText(), /0:00.800/);
  await page.getByRole('slider', { name: '视频入点', exact: true }).focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await dialog.count(), 1); assert.ok(Number(await start.inputValue()) > 1.1);
  await start.fill('1.1');
  await page.setViewportSize({ width: 480, height: 800 });
  await page.screenshot({ path: `${dir}/trim-narrow.png` });
  assert.ok(await page.locator('.video-player').evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.evaluate(() => { window.failNodeSave = true; });
  await page.getByRole('button', { name: '另存为新视频', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  assert.equal(encodes, 1);
  await page.evaluate(() => { window.failNodeSave = false; });
  await page.getByRole('button', { name: '另存为新视频', exact: true }).click();
  await page.getByText('新视频已保存到画板', { exact: true }).waitFor();
  assert.equal(encodes, 1, 'node retry must not encode/import twice');
  assert.equal((await copies()).length, 1);
  assert.equal((await page.evaluate(() => window.snapshot())).nodes.length, 2);
  assert.equal(await dialog.locator('video').evaluate(video => video.duration), 3, 'save-as retains original video');
  await page.evaluate(() => { window.failVideoTrim = true; });
  await page.getByRole('button', { name: '覆盖原视频', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  await page.waitForFunction(() => document.querySelector('.video-player video')?.readyState >= 2);
  assert.equal(await dialog.locator('video').evaluate(video => video.duration), 3, 'failed overwrite reloads original');
  assert.equal(await start.inputValue(), '1.1'); assert.equal(await end.inputValue(), '1.9');
  await page.evaluate(() => { window.failVideoTrim = false; window.holdVideoTrim = true; });
  await start.fill('0.3'); await end.fill('1.2');
  await page.getByRole('button', { name: '覆盖原视频', exact: true }).click();
  await page.waitForFunction(() => typeof window.releaseVideoTrim === 'function');
  assert.equal(await dialog.locator('video').getAttribute('src'), null, 'release source before replacement');
  assert.equal(await page.getByRole('button', { name: '正在覆盖…', exact: true }).isDisabled(), true);
  await page.evaluate(() => { window.holdVideoTrim = false; window.releaseVideoTrim(); });
  await page.getByText('原视频已覆盖', { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.video-player video')?.readyState >= 2);
  assert.ok(await dialog.locator('video').evaluate(video => Math.abs(video.duration - 0.9) < 0.05));
  assert.equal((await page.evaluate(() => window.snapshot())).nodes.length, 2, 'overwrite keeps node identity');
  await page.getByRole('button', { name: '裁剪视频', exact: true }).click();
  await start.fill('0.1'); await end.fill('0.7');
  await page.evaluate(() => { window.holdVideoTrim = true; window.releaseVideoTrim = null; });
  await page.getByRole('button', { name: '另存为新视频', exact: true }).click();
  await page.waitForFunction(() => typeof window.releaseVideoTrim === 'function');
  await page.keyboard.press('Escape');
  await page.evaluate(async () => {
    const { useStore } = await import('/src/store.ts');
    useStore.setState({ activeProjectId: 'q', projectRouteRevision: useStore.getState().projectRouteRevision + 1 });
    window.holdVideoTrim = false; window.releaseVideoTrim();
  });
  await page.waitForFunction(() => window.snapshot().nodes.length === 3);
  assert.equal((await page.evaluate(() => window.snapshot())).nodes.at(-1).projectId, 'p');
  assert.equal(await page.locator('[data-canvas-node-id]').count(), 0, 'late video copy must not appear in another project');
  await page.evaluate(() => window.save()); await page.reload();
  assert.equal((await page.evaluate(() => window.snapshot())).nodes.length, 3);
  assert.deepEqual(errors, []);
  console.log('PASS trim range/keyboard, save-as, placement retry without re-encode, failed overwrite preservation, source release, reload and layout');
} finally { await browser.close(); await server.close(); }
