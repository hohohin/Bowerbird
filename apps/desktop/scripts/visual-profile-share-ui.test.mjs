  const exportButton=dialog.getByRole('button',{name:'导出分享',exact:true});
  await exportButton.click();
  await page.getByRole('status').filter({hasText:'已导出'}).waitFor();
  assert.equal(await calls('visual_profile_export'),1);
  await page.evaluate(()=>window.exportPath=null);
  await exportButton.click(); await exportButton.waitFor();
