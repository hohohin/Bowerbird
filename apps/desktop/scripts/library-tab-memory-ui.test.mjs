import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { createServer } from "vite";
import { chromium } from "../../html-renderer/node_modules/playwright/index.mjs";

const output = ".tmp/library-tab-memory";
await mkdir(output, { recursive: true });
const server = await createServer({ cacheDir: `${output}/vite`, server: { host: "127.0.0.1", port: 0, strictPort: false, hmr: false, watch: null } });
await server.listen();
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" });
page.setDefaultTimeout(15000);
page.setDefaultNavigationTimeout(60000);
const errors = [];
page.on("pageerror", error => errors.push(error.message));
await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
const url = `${server.resolvedUrls.local[0]}scripts/fixtures/`;
const mainFixture = url + "home-navigation-live/preview.html?source-library&detail-route&canvas-library&media-home";
const home = page.locator('.home-workspace-page[data-suspended="false"] .library-home');
const panel = page.locator('.canvas-source-panel[aria-hidden="false"]');
const nav = page.getByRole("navigation", { name: "首页" });
const side = root => root.getByRole("complementary", { name: "素材库导航", exact: true });
const button = (root, name) => side(root).getByRole("button", { name, exact: true });
const toggle = (root, mode) => side(root).getByRole("button", { name: mode, exact: true, pressed: true }).waitFor();
const openProject = async () => {
  await nav.getByRole("button", { name: "项目", exact: true }).click();
  await page.getByRole("button", { name: "打开项目 山野品牌 1", exact: true }).click();
  await page.locator('.canvas-workspace[aria-busy="false"]').waitFor();
};
const goHome = async () => {
  await page.getByRole("button", { name: "返回主页", exact: true }).click();
  await nav.getByRole("button", { name: "素材库", exact: true }).click();
};
try {
  await page.goto(mainFixture);
  await button(home, "全部素材").waitFor();
  await button(home, "秋日海报 2").click();
  await button(home, "标签模式").click();
  await page.reload();
  await toggle(home, "标签模式");
  await button(home, "层级模式").click();
  assert.equal(await button(home, "秋日海报 2").getAttribute("aria-current"), "true");

  await openProject();
  await page.locator(".canvas-stage").focus();
  await page.keyboard.press("Tab");
  await button(panel, "收起侧栏").waitFor();
  assert.equal(await button(panel, "山野品牌 1").getAttribute("aria-current"), "true");
  const drawerBox = await panel.boundingBox();
  const sidebarBox = await side(panel).boundingBox();
  await page.keyboard.press("e");
  await toggle(panel, "标签模式");
  assert.deepEqual(await panel.boundingBox(), drawerBox);
  assert.deepEqual(await side(panel).boundingBox(), sidebarBox);
  await page.keyboard.press("q");
  await button(panel, "秋日海报 2").click();
  assert.equal(await page.evaluate(() => window.store.getState().activeProjectId), "p");
  await button(panel, "回到当前项目").click();
  assert.equal(await button(panel, "山野品牌 1").getAttribute("aria-current"), "true");
  await button(panel, "文件夹").click();
  await button(panel, "收起侧栏").click();
  await page.locator(".canvas-stage").focus();
  await page.keyboard.press("Tab");
  await panel.waitFor({ state: "hidden" });
  await page.locator(".canvas-stage").focus();
  await page.keyboard.press("Tab");
  await button(panel, "展开侧栏").click();
  assert.equal(await button(panel, "文件夹").getAttribute("aria-current"), "true");
  await page.screenshot({ path: `${output}/canvas.png` });

  await goHome();
  assert.equal(await button(home, "秋日海报 2").getAttribute("aria-current"), "true");
  await button(home, "标签模式").click();
  await button(home, "收起侧栏").click();
  await home.getByRole("button", { name: "向右分栏", exact: true }).click();
  const left = home.locator('[data-library-pane="home-left"]'), right = home.locator('[data-library-pane="home-pane-1"]');
  await button(left, "展开侧栏").waitFor();
  await button(right, "展开侧栏").click();
  await toggle(right, "标签模式");
  await page.keyboard.press("q");
  assert.equal(await button(right, "秋日海报 2").getAttribute("aria-current"), "true");
  await button(right, "文件夹").click();
  await button(left, "展开侧栏").click();
  await toggle(left, "标签模式");
  assert.equal(await button(right, "文件夹").getAttribute("aria-current"), "true");
  await left.locator(".catalog-scroller [data-asset-id]").first().waitFor();
  await page.waitForFunction(() => {
    const view = document.querySelector('[data-library-pane="home-left"] .catalog-scroller');
    const bounds = view.getBoundingClientRect();
    return [...view.querySelectorAll("[data-asset-id]")].every(card => card.getBoundingClientRect().right <= bounds.right + 1);
  });
  await page.screenshot({ path: `${output}/split.png` });

  await page.goto(url + "catalog-paging/preview.html?text");
  const text = page.getByRole("complementary", { name: "文本编辑器素材库", exact: true });
  await button(text, "收起侧栏").waitFor();
  await button(text, "项目A").focus();
  await page.keyboard.press("e");
  await toggle(text, "标签模式");
  await page.keyboard.press("Tab");
  await toggle(text, "标签模式");
  await page.keyboard.press("q");
  await toggle(text, "层级模式");
  await button(text, "层级模式").evaluate(control => control.dispatchEvent(new KeyboardEvent("keydown", { key: "e", isComposing: true, bubbles: true })));
  await toggle(text, "层级模式");
  await text.getByRole("button", { name: "搜索素材", exact: true }).click();
  const search = text.getByRole("searchbox");
  await search.press("e");
  assert.equal(await search.inputValue(), "e");
  await toggle(text, "层级模式");
  await search.press("Escape");
  await button(text, "收起侧栏").click();
  await page.reload();
  await button(text, "展开侧栏").waitFor();
  assert.deepEqual(errors, []);
  console.log("PASS independent pane memory and copying, canvas Tab, text workspace Q/E and input protection");
} catch (error) {
  console.error(error, errors);
  await page.screenshot({ path: `${output}/failure.png` }).catch(() => {});
  throw error;
} finally {
  await browser.close(); server.httpServer?.closeAllConnections(); await server.close();
}
