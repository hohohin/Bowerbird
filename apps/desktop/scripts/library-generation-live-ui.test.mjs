import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from '../../html-renderer/node_modules/playwright/index.mjs';
const server = await createServer({ server: { host: '127.0.0.1', port: 17945, strictPort: true, hmr: false, watch: null } });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.setDefaultTimeout(8000);
const errors = [], remote = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('**/*', route => {
  if (new URL(route.request().url()).hostname === '127.0.0.1') return route.continue();
  remote.push(route.request().url()); return route.abort();
});
try {
  await page.goto(`${server.resolvedUrls.local[0]}scripts/fixtures/library-generation-live/preview.html?source-library&detail-route&canvas-library`);
  await page.locator('.canvas-workspace[aria-busy="false"]').waitFor();
  await page.getByRole('button', { name: '返回主页', exact: true }).click();
  const composer = page.getByRole('region', { name: '素材库创作', exact: true });
  await composer.waitFor();
  const editor = composer.locator('.ProseMirror');
  assert.equal(await page.evaluate(() => window.preparedProjects.length), 0);
  await editor.fill('主屏直接生成一张海报');
  const libraryAsset = page.locator('.library-home [data-asset-id]').first();
  const referenceId = await libraryAsset.getAttribute('data-asset-id');
  await libraryAsset.click();
  await editor.locator(`[data-asset-id="${referenceId}"]`).waitFor();
  const scopeBefore = await page.evaluate(() => window.calls.filter(call => call.command === 'set_active_project').length);
  await composer.locator('.composer-send button').click();
  await page.waitForFunction(() => window.generationCalls.length === 1);
  assert.equal(await page.evaluate(() => window.generationCalls[0].projectId), 'quick-live');
  assert.equal(await page.evaluate(() => window.generationCalls[0].referenceImages.length), 1, 'clicked library asset reaches the real generation request');
  assert.equal(await page.evaluate(() => window.store.getState().activeProjectId), null);
  assert.equal(await page.evaluate(() => window.nativeProject), null);
  assert.equal(await page.evaluate(() => window.calls.filter(call => call.command === 'set_active_project').length), scopeBefore, 'background send does not change native scope');
  await editor.fill('保留在素材库的下一条草稿');
  const first = await page.evaluate(() => window.completeGeneration(0));
  const toast = page.getByRole('status').filter({ hasText: '快速生成 · 图片生成完成' });
  await toast.getByRole('button', { name: /查看画板$/ }).click();
  await page.locator('.canvas-workspace[aria-busy="false"]').waitFor();
  const prompt = page.locator(`[data-canvas-node-id="${first.promptId}"]`);
  await prompt.waitFor();
  await page.waitForFunction(id => window.store.getState().focusedThreadId === id, first.threadId);
  assert.equal(await page.evaluate(() => window.store.getState().activeProjectId), first.projectId);
  assert.equal(await composer.count(), 0, 'library editor unmounts in canvas');
  await page.getByRole('button', { name: '返回主页', exact: true }).click();
  await composer.waitFor();
  assert.ok((await editor.innerText()).includes('下一条草稿'), 'library draft restored after task visit');

  const nav = page.getByRole('navigation', { name: '首页' });
  await nav.getByRole('button', { name: '项目', exact: true }).click();
  assert.equal(await composer.count(), 0, 'project page does not keep a hidden consuming editor');
  await nav.getByRole('button', { name: '素材库', exact: true }).click();
  await composer.waitFor();
  await composer.getByRole('combobox', { name: '选择项目', exact: true }).click();
  await page.getByRole('option', { name: '秋日海报 2', exact: true }).click();
  await editor.fill('指定项目的独立生成');
  await composer.locator('.composer-send button').click();
  await page.waitForFunction(() => window.generationCalls.length === 2);
  assert.equal(await page.evaluate(() => window.generationCalls[1].projectId), 'home-project-1');
  assert.equal(await page.evaluate(() => window.store.getState().activeProjectId), null);
  assert.equal(await page.evaluate(() => window.nativeProject), null);

  await mkdir('.tmp/library-generation-live', { recursive: true });
  for (const width of [900, 1440]) for (const theme of ['dark', 'light']) {
    await page.setViewportSize({ width, height: 900 });
    await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
    await editor.click();
    const activity = await page.locator('.library-home-activity summary').boundingBox();
    const heading = await page.locator('.library-home .file-view-heading').boundingBox();
    assert.ok(activity.y >= heading.y + heading.height, 'recent tasks stay below media and catalog controls');
    const scroller = page.locator('.library-home .catalog-scroller');
    await scroller.evaluate(element => { element.scrollTop = element.scrollHeight; });
    const lastAssetId = await page.evaluate(() => window.lastLibraryAssetId);
    const lastAsset = page.locator(`.library-home [data-asset-id="${lastAssetId}"]`).last();
    await lastAsset.waitFor();
    const bottomAsset = await lastAsset.boundingBox();
    const composerBounds = await composer.boundingBox();
    assert.ok(bottomAsset.y + bottomAsset.height <= composerBounds.y, 'last library row can scroll above the composer');
    const referencesBefore = await editor.locator(`[data-asset-id="${lastAssetId}"]`).count();
    await lastAsset.click();
    await page.waitForFunction(({ id, count }) => document.querySelectorAll(`.library-composer .ProseMirror [data-asset-id="${id}"]`).length > count, { id: lastAssetId, count: referencesBefore });
    await scroller.evaluate(element => { element.scrollTop = 0; });
    await composer.getByRole('combobox', { name: '选择项目', exact: true }).click();
    const menu = page.getByRole('listbox', { name: '选择项目', exact: true });
    await menu.waitFor();
    const bounds = await menu.boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width + 1 && bounds.y >= 0 && bounds.y + bounds.height <= 901, 'project menu stays in viewport');
    await page.screenshot({ path: `.tmp/library-generation-live/${theme}-${width}.png` });
    await page.keyboard.press('Escape');
  }
  assert.deepEqual(errors, []);
  assert.deepEqual(remote, []);
  console.log('PASS: actual App library submission, frozen native scope, completion toast routing, restored draft, hidden-editor lifecycle and responsive themes');
} catch (error) {
  console.log('UI errors', errors);
  console.log((await page.locator('body').innerText()).slice(-3500));
  throw error;
} finally { await browser.close(); await server.close(); }
