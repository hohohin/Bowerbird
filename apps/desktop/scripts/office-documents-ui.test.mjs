async function drop(selector, names, point) {
  await page.locator(selector).first().evaluate((element, { names, point }) => {
    const dataTransfer = new DataTransfer();
    names.forEach(name => dataTransfer.items.add(new File(['isolated transport fixture'], name)));
    const rect = element.getBoundingClientRect();
    const at = point ?? { x: rect.x + rect.width / 2, y: rect.y + rect.height / 2 };
    for (const type of ['dragover', 'drop']) element.dispatchEvent(new DragEvent(type, { bubbles: true, cancelable: true, dataTransfer, clientX: at.x, clientY: at.y }));
  }, { names, point });
}
