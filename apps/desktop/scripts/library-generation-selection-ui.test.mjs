import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { chromium } from '../../html-renderer/node_modules/playwright/index.mjs';

const server = await createServer({ server: { host: '127.0.0.1', port: 17958, strictPort: true, hmr: false, watch: null } });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.setDefaultTimeout(5000);
  await page.goto(`${server.resolvedUrls.local[0]}scripts/fixtures/library-creation-parity/preview.html?source-library&detail-route&canvas-library`);
  await page.locator('.canvas-workspace[aria-busy="false"]').waitFor();
  await page.getByRole('button', { name: '返回主页', exact: true }).click();
  const composer = page.getByRole('region', { name: '素材库创作', exact: true });
  const editor = composer.locator('.ProseMirror');
  const preview = page.getByRole('dialog', { name: '图片与会话预览', exact: true });
  await editor.fill('参考这些素材');
  const cards = page.locator('.library-home [data-asset-id]');
  await cards.first().waitFor();
  const id = await cards.first().getAttribute('data-asset-id');
  await cards.first().click();
  await preview.waitFor();
  assert.equal(await editor.locator('[data-asset-id]').count(), 0, 'single click previews without attaching');
  await page.keyboard.press('Escape'); await preview.waitFor({ state: 'detached' });
  await cards.first().dblclick();
  await editor.locator(`[data-asset-id="${id}"]`).waitFor();
  await page.waitForTimeout(700);
  assert.equal(await preview.count(), 0, 'double click attaches without delayed preview');
  assert.equal(await page.getByRole('dialog', { name: /媒体预览/ }).count(), 0, 'double click does not open ordinary details');
  assert.equal(await page.evaluate(() => window.parityPicks.length), 1, 'double click attaches exactly once');
  assert.equal(await page.evaluate(() => window.generationCalls.length), 0, 'attachment never submits');
  const count = await editor.locator('[data-asset-id]').count();
  await cards.nth(1).click({ modifiers: ['Control'] });
  assert.equal(await editor.locator('[data-asset-id]').count(), count, 'multi-selection does not attach');
  await page.locator('.catalog-selection').getByRole('button', { name: /取消/ }).click();
  await page.getByRole('button', { name: '退出创作模式', exact: true }).click();
  await cards.first().click();
  await page.getByRole('dialog', { name: /媒体预览/ }).waitFor();
  await page.keyboard.press('Escape'); await page.locator('.media-lightbox').waitFor({ state: 'detached' });
  await editor.focus();
  await page.locator('.library-home').getByRole('tab', { name: '文件夹', exact: true }).click();
  const connected = page.locator('[data-connection-entry="parity-entry-1"] .folder-media-card');
  await connected.waitFor();
  await connected.click();
  await preview.waitFor();
  assert.equal(await editor.locator('[data-asset-id]').count(), count, 'connected single click also previews without attaching');
  await page.keyboard.press('Escape'); await preview.waitFor({ state: 'detached' });
  await connected.dblclick();
  await page.waitForFunction(() => window.parityPicks.length === 2);
  await page.waitForTimeout(700);
  assert.equal(await page.evaluate(() => window.parityPicks.length), 2, 'home connected collection attaches exactly once in creation mode');
  assert.equal(await editor.locator('[data-asset-id]').count(), count + 1);
  assert.equal(await page.getByRole('dialog').count(), 0);
  await composer.getByRole('button', { name: '退出创作模式', exact: true }).click();
  await connected.click();
  await page.getByRole('dialog', { name: /媒体预览/ }).waitFor();
  assert.equal(await page.evaluate(() => window.generationCalls.length), 0);
  assert.equal(await page.evaluate(() => window.preparedProjects.length), 0, 'preview and attachment do not prepare a project');
  assert.ok((await editor.innerText()).includes('参考这些素材'), 'draft survives both library modes');
  console.log('PASS: real App catalog and connected collection single preview/double reference, multi-selection, browsing, draft and no automatic submission');
} finally { await browser.close(); await server.close(); }
