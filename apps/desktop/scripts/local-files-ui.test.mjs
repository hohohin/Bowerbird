  await page.mouse.move(sourceBox.x + 50, sourceBox.y + 40, { steps: 6 });
  await page.mouse.move(stageBox.x + stageBox.width * .7, stageBox.y + stageBox.height * .7, { steps: 20 }); await page.mouse.up();
