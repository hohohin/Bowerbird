import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '../../html-renderer/node_modules/playwright/index.mjs';
import { createServer } from 'vite';

const server = await createServer({ server: { host: '127.0.0.1', port: 1599, strictPort: true, hmr: false, watch: null } });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 850 } });
  page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${server.resolvedUrls.local[0]}scripts/fixtures/quick-transfer-desktop/preview.html`);
  await page.getByRole('button', { name: '快传', exact: true }).click();
  await page.getByRole('tab', { name: '接收', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab', { name: '发送', exact: true }).getAttribute('aria-selected'), 'true');
  const toggle = page.getByRole('switch', { name: '发送开关' });
  assert.equal(await toggle.isDisabled(), true);
  await page.evaluate(() => { window.cancelPicker = true; });
  await page.getByRole('button', { name: '选择文件', exact: true }).click();
  assert.equal(await toggle.isDisabled(), true);
  await page.evaluate(() => { window.cancelPicker = false; window.pickFiles = ['D:\\素材\\照片.heic', 'D:\\笔记.txt']; });
  await page.getByRole('button', { name: '选择文件', exact: true }).click();
  await page.getByRole('button', { name: '移除 笔记.txt', exact: true }).click();
  await toggle.click();
  await page.getByText('发送已开启', { exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => window.calls.find(c => c.command === 'quick_transfer_send_start').args.files), ['D:\\素材\\照片.heic']);
  await page.getByRole('img', { name: '扫码下载文件' }).waitFor();
  await page.getByRole('button', { name: '复制下载地址' }).click();
  assert.match(await page.evaluate(() => window.copiedAddress), /53318\/\?pin=87654321$/);
  await page.getByRole('tab', { name: '接收', exact: true }).click();
  await page.getByRole('switch', { name: '接收开关' }).click();
  await page.getByText('接收已开启', { exact: true }).waitFor();
  await page.getByRole('button', { name: '收起快传面板' }).click();
  assert.equal(await page.evaluate(() => window.calls.filter(c => c.command.endsWith('_stop')).length), 0);
  await page.getByRole('button', { name: '快传', exact: true }).click();
  await page.getByRole('tab', { name: '发送', exact: true }).click();
  await mkdir('.tmp/quick-transfer-send', { recursive: true });
  await page.screenshot({ path: '.tmp/quick-transfer-send/desktop-dark.png' });
  await page.evaluate(() => document.documentElement.dataset.theme = 'light');
  await page.setViewportSize({ width: 420, height: 800 });
  await page.screenshot({ path: '.tmp/quick-transfer-send/desktop-light-narrow.png' });
  assert.equal(await page.locator('.quick-transfer-content').evaluate(node => node.scrollWidth <= node.clientWidth), true);
  await toggle.click();
  await page.getByText('发送已关闭', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.snapshot.active), true, 'stopping send preserves receive');
  assert.deepEqual(errors, []);
  console.log('send UI: select/cancel/remove, original paths, QR/copy, independent switches, collapse, themes passed');
} finally { await browser.close(); await server.close(); }
