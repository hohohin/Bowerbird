  assert.equal(await page.evaluate(()=>window.fixtureStore.getState().activeVisualProfileId),null);
  await mkdir('.tmp/visual-profile-sharing',{recursive:true});
  await page.waitForTimeout(400);
  await page.screenshot({path:'.tmp/visual-profile-sharing/imported.png'});
  await dialog.getByRole('button',{name:'保存规范',exact:true}).click();
